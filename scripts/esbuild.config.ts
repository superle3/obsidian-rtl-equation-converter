/// <reference types="node" />
import fs from "node:fs";
import { builtinModules } from "node:module";
import path from "node:path";
import process from "node:process";
import esbuild from "esbuild";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;
const outDir = process.env.OUTDIR ?? ".";

function debouncer<A, R>(func: (...args: A[]) => R, wait: number) {
	let timeout: NodeJS.Timeout;
	return (...args: A[]) => {
		clearTimeout(timeout);
		timeout = setTimeout(() => func(...args), wait);
	};
}

const watchCopyFile = (src: string, dest: string) => {
	if (path.resolve(src) === path.resolve(dest)) {
		return () => {};
	}
	const debouncedCopy = debouncer((_) => {
		console.log(`Copied ${src} to ${dest}`);
		fs.copyFileSync(src, dest);
	}, 1000);
	debouncedCopy();
	return fs.watchFile(src, debouncedCopy);
};

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2021",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: path.join(outDir, "main.js"),
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	if (path.resolve(".") !== path.resolve(outDir)) {
		watchCopyFile("manifest.json", path.join(outDir, "manifest.json"));
	}
	await context.watch();
}
